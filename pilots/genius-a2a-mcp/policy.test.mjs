import test from 'node:test';
import assert from 'node:assert/strict';
import { decide, fallback } from './policy.mjs';
const yellow={scopeApproved:true,maxRequests:3,publicOnly:true};
const orange={scopeApproved:true,exactHeadTestsPassed:true,independentReviewApproved:true,rollbackReady:true};
test('safe offline docs permitted',()=>assert.equal(decide('docs.write').allow,true));
test('unknown action denied',()=>assert.equal(decide('unlisted.tool').allow,false));
test('public read requires bounded scope',()=>assert.equal(decide('public.read').allow,false));
test('bounded public read permitted',()=>assert.equal(decide('public.read',yellow).allow,true));
test('explicit denial overrides public scope',()=>assert.equal(decide('public.read',{...yellow,explicitDeny:true}).allow,false));
test('too many requests denied',()=>assert.equal(decide('public.read',{...yellow,maxRequests:100}).allow,false));
test('nonpublic outreach denied',()=>assert.equal(decide('outreach.nonbinding',{...yellow,publicOnly:false}).allow,false));
test('deployment without review denied',()=>assert.equal(decide('deploy.production',{...orange,independentReviewApproved:false}).allow,false));
test('deployment with all declared gates permitted for downstream review',()=>assert.equal(decide('deploy.production',orange).allow,true));
test('financial transfer never autoauthorized',()=>assert.equal(decide('funds.transfer',orange).allow,false));
test('contract acceptance never autoauthorized',()=>assert.equal(decide('contract.accept',orange).allow,false));
test('government private access never autoauthorized',()=>assert.equal(decide('government.private_access',orange).allow,false));
test('transient retries bounded',()=>assert.equal(fallback('transient',{attempts:3}).retry,false));
test('transient backoff',()=>assert.equal(fallback('transient',{attempts:1}).route,'BACKOFF'));
test('permission denial does not bypass',()=>assert.equal(fallback('permission_denied').route,'PREPARE_PATCH_AND_REQUEST_REVIEW'));
test('policy block stops',()=>assert.equal(fallback('policy_blocked',{attempts:0}).route,'STOP_AND_REVIEW'));
test('explicit denial overrides retry',()=>assert.equal(fallback('transient',{attempts:0,explicitDeny:true}).retry,false));
