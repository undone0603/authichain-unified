#!/usr/bin/env node
/**
 * Embed content/microsites/<slug>/index.html into
 * workers/authichain-com/src/microsite-packs.ts so wrangler can bundle
 * the bytes without a runtime filesystem.
 *
 * Usage: node scripts/sync-microsite-packs.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(
  readFileSync(join(root, "content/microsites/manifest.json"), "utf8"),
);

const entries = manifest.packs.map((pack) => {
  const html = readFileSync(join(root, "content/microsites", pack.file), "utf8");
  if (!html.includes("api/checkout/")) {
    throw new Error(`${pack.file} is missing a checkout href`);
  }
  return `  ${JSON.stringify(pack.slug)}: ${JSON.stringify(html)}`;
});

const out = `/* Generated by scripts/sync-microsite-packs.mjs — do not edit by hand. */
export const MICROSITE_HTML: Record<string, string> = {
${entries.join(",\n")},
};
`;

const dest = join(root, "workers/authichain-com/src/microsite-packs.ts");
writeFileSync(dest, out);
console.log(`wrote ${dest} (${manifest.packs.length} packs)`);
