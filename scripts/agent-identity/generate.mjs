/**
 * Generate public identity records for AuthiChain's own bots.
 *
 *   KEY_DIR=/path/outside/repo node scripts/agent-identity/generate.mjs
 *
 * Private keys live ONLY in KEY_DIR (outside the repo, mode 0600) and are
 * never printed or written to the output. Missing keys are created; existing
 * keys are reused, so re-running is stable. The output file holds public
 * material only: names, roles, did:key / did:web ids, and one Ed25519-signed
 * identity record per bot that protocol/verifier.mjs checks offline.
 *
 * The AuthiChain agent issuer key signs each bot's record. Each bot key also
 * signs a short self-statement, proving the bot's key pair is controlled by us.
 */
import { generateKeyPairSync, createPrivateKey, createPublicKey, sign as edSign } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync, chmodSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { canonicalize, signingBytes, verifyRecord } from '../../protocol/verifier.mjs';
import { BOTS, ISSUER_SLUG, VALID_FROM, VALID_UNTIL } from './bots.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '../../workers/authichain-com/src/bot-identities.ts');
const KEY_DIR = process.env.KEY_DIR;
if (!KEY_DIR) { console.error('KEY_DIR is required (a directory outside the repo)'); process.exit(2); }
mkdirSync(KEY_DIR, { recursive: true, mode: 0o700 });
chmodSync(KEY_DIR, 0o700);

const B58 = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
function b58(buf) {
  let n = BigInt('0x' + (Buffer.from(buf).toString('hex') || '0'));
  let o = '';
  while (n > 0n) { o = B58[Number(n % 58n)] + o; n /= 58n; }
  for (const b of buf) { if (b !== 0) break; o = '1' + o; }
  return o;
}

function loadKey(slug) {
  const p = join(KEY_DIR, `${slug}.ed25519.pem`);
  if (!existsSync(p)) {
    const { privateKey } = generateKeyPairSync('ed25519');
    writeFileSync(p, privateKey.export({ format: 'pem', type: 'pkcs8' }), { mode: 0o600 });
  }
  chmodSync(p, 0o600);
  const privateKey = createPrivateKey(readFileSync(p));
  const raw = createPublicKey(privateKey).export({ format: 'der', type: 'spki' }).subarray(-32);
  const multibase = 'z' + b58(Buffer.concat([Buffer.from([0xed, 0x01]), raw]));
  return { privateKey, multibase, didKey: `did:key:${multibase}`, jwkX: raw.toString('base64url') };
}

function signRecord(record, key) {
  const unsigned = { ...record };
  delete unsigned.proof;
  const proofBase = {
    type: 'Ed25519Signature2020',
    created: VALID_FROM,
    verificationMethod: `${key.didKey}#${key.multibase}`,
    proofPurpose: 'assertionMethod',
  };
  const withProof = { ...unsigned, proof: proofBase };
  const sig = edSign(null, signingBytes(withProof), key.privateKey);
  return { ...unsigned, proof: { ...proofBase, proofValue: 'z' + b58(sig) } };
}

const issuer = loadKey(ISSUER_SLUG);
const bots = BOTS.map((bot) => {
  const key = loadKey(bot.slug);
  const didWeb = `did:web:authichain.com:agents:${bot.slug}`;
  const record = signRecord({
    '@context': ['https://www.w3.org/ns/credentials/v2', 'https://authichain.com/protocol/v1'],
    type: ['VerifiableCredential', 'AgentIdentityRecord'],
    issuer: issuer.didKey,
    validFrom: VALID_FROM,
    validUntil: VALID_UNTIL,
    credentialSubject: {
      id: didWeb,
      name: bot.name,
      role: bot.role,
      operator: 'AuthiChain',
      isHuman: false,
      agentKey: key.didKey,
      profile: `https://authichain.com/agents/${bot.slug}`,
    },
  }, issuer);
  // The bot's own key signs a short statement: proof we hold this key.
  const selfStatement = signRecord({
    '@context': ['https://www.w3.org/ns/credentials/v2', 'https://authichain.com/protocol/v1'],
    type: ['VerifiableCredential', 'AgentKeyControlStatement'],
    issuer: key.didKey,
    validFrom: VALID_FROM,
    validUntil: VALID_UNTIL,
    credentialSubject: {
      id: didWeb,
      statement: `I am ${bot.name}, an AI agent operated by AuthiChain. I am not a person.`,
    },
  }, key);
  for (const r of [record, selfStatement]) {
    const v = verifyRecord(r);
    if (v.verdict !== 'valid-unanchored') throw new Error(`self-check failed for ${bot.slug}: ${v.reasons}`);
  }
  return { ...bot, did: didWeb, didKey: key.didKey, publicKeyMultibase: key.multibase, publicKeyJwkX: key.jwkX, record, selfStatement };
});

const out = {
  generatedFrom: 'scripts/agent-identity/generate.mjs',
  issuer: { slug: ISSUER_SLUG, did: 'did:web:authichain.com', didKey: issuer.didKey, publicKeyMultibase: issuer.multibase, publicKeyJwkX: issuer.jwkX },
  bots,
};
writeFileSync(OUT, '// GENERATED by scripts/agent-identity/generate.mjs. Public keys and signed records only.\n/* eslint-disable */\nexport const BOT_IDENTITIES = ' + JSON.stringify(out, null, 2) + ';\n');
console.log(`wrote ${bots.length} public identities to ${OUT} (no private keys)`);
