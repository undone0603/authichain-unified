/**
 * Re-issue AgentZ's public identity with its own key, leaving every other bot
 * (and its Polygon anchor) untouched.
 *
 *   KEY_DIR=/path/outside/repo node scripts/agent-identity/rotate-agentz.mjs
 *
 * Used when the shared agent issuer key is unavailable. AgentZ's record is
 * self-issued (issuer = AgentZ's did:key) and marked `selfIssued: true`, so
 * checkBot and the identity pages say exactly that rather than claiming the
 * AuthiChain issuer signed it. KEY_DIR/agentz.ed25519.pem must already exist;
 * this script never creates a key. Public material only is written.
 */
import {
  createPrivateKey,
  createPublicKey,
  createHash,
  sign as edSign,
} from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { signingBytes, verifyRecord } from "../../protocol/verifier.mjs";

export const VALID_FROM = "2026-11-19T00:00:00Z";
export const VALID_UNTIL = "2027-11-19T00:00:00Z";
const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "../../workers/authichain-com/src/bot-identities.ts");
const B58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";

function b58(buf) {
  let n = BigInt("0x" + (Buffer.from(buf).toString("hex") || "0"));
  let o = "";
  while (n > 0n) {
    o = B58[Number(n % 58n)] + o;
    n /= 58n;
  }
  for (const b of buf) {
    if (b !== 0) break;
    o = "1" + o;
  }
  return o;
}

function sign(record, key) {
  const unsigned = { ...record };
  delete unsigned.proof;
  const proofBase = {
    type: "Ed25519Signature2020",
    created: VALID_FROM,
    verificationMethod: `${key.didKey}#${key.multibase}`,
    proofPurpose: "assertionMethod",
  };
  const sig = edSign(
    null,
    signingBytes({ ...unsigned, proof: proofBase }),
    key.privateKey
  );
  return { ...unsigned, proof: { ...proofBase, proofValue: "z" + b58(sig) } };
}

const KEY_DIR = process.env.KEY_DIR;
if (!KEY_DIR) {
  console.error("KEY_DIR is required");
  process.exit(2);
}
const pem = join(KEY_DIR, "agentz.ed25519.pem");
if (!existsSync(pem)) {
  console.error(`${pem} not found; this script never creates keys`);
  process.exit(2);
}
const privateKey = createPrivateKey(readFileSync(pem));
const raw = createPublicKey(privateKey)
  .export({ format: "der", type: "spki" })
  .subarray(-32);
const multibase = "z" + b58(Buffer.concat([Buffer.from([0xed, 0x01]), raw]));
const jwkX = raw.toString("base64url");
const kid = createHash("sha256")
  .update(`{"crv":"Ed25519","kty":"OKP","x":"${jwkX}"}`)
  .digest("base64url");
const key = { privateKey, multibase, didKey: `did:key:${multibase}` };

const src = readFileSync(OUT, "utf8");
const data = JSON.parse(src.slice(src.indexOf("=") + 1, src.lastIndexOf(";")));
const i = data.bots.findIndex(b => b.slug === "agentz");
if (i < 0) throw new Error("agentz not found");
const old = data.bots[i];

const record = sign(
  {
    "@context": old.record["@context"],
    type: old.record.type,
    issuer: key.didKey,
    validFrom: VALID_FROM,
    validUntil: VALID_UNTIL,
    credentialSubject: {
      ...old.record.credentialSubject,
      agentKey: key.didKey,
    },
  },
  key
);
const selfStatement = sign(
  {
    "@context": old.selfStatement["@context"],
    type: old.selfStatement.type,
    issuer: key.didKey,
    validFrom: VALID_FROM,
    validUntil: VALID_UNTIL,
    credentialSubject: old.selfStatement.credentialSubject,
  },
  key
);
for (const [name, r] of [
  ["record", record],
  ["selfStatement", selfStatement],
]) {
  const v = verifyRecord(r, null, { now: new Date(VALID_FROM) });
  if (v.verdict !== "valid-unanchored")
    throw new Error(`self-check failed for ${name}: ${v.reasons}`);
}
data.bots[i] = {
  ...old,
  didKey: key.didKey,
  publicKeyMultibase: multibase,
  publicKeyJwkX: jwkX,
  kid,
  selfIssued: true,
  record,
  selfStatement,
};
const body =
  "// GENERATED by scripts/agent-identity/generate.mjs. Public keys and signed records only.\n/* eslint-disable */\nexport const BOT_IDENTITIES = " +
  JSON.stringify(data, null, 2) +
  ";\n";
if (/PRIVATE KEY|"d"\s*:/.test(body))
  throw new Error("refusing to write private material");
writeFileSync(OUT, body);
console.log(
  `re-issued agentz as ${key.didKey} (self-issued, ${VALID_FROM} to ${VALID_UNTIL}); ${data.bots.length - 1} other bots unchanged`
);
