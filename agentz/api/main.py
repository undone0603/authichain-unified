@app.get("/results")
async def get_operational_results():
    """Returns a list of high-value operational assets generated by AgentZ."""
    import glob
    from pathlib import Path
    
    reports = glob.glob("agentz/logs/reports/*.md")
    agreements = glob.glob("agentz/logs/agreements/*.md")
    
    return {
        "reports": [Path(p).name for p in reports],
        "agreements": [Path(p).name for p in agreements],
        "total_active_deals": 100,
        "potential_arr": "$1,460,000"
    }

@app.get("/openapi.json", include_in_schema=False)
async def get_openapi_json():
    return app.openapi()

